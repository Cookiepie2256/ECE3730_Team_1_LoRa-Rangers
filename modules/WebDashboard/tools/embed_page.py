"""Turn web/index.html into WebDashboardPage.h for the ESP32.

Run after every change to the page:
    python tools/embed_page.py           # writes WebDashboardPage.h
    python tools/embed_page.py --check   # fails if the header is out of date

The page is stored in flash as one raw string. A light minify (strip
indentation, blank lines and whole-line // comments) keeps it small.
"""

import argparse
import sys
from pathlib import Path

MODULE = Path(__file__).resolve().parent.parent
SRC = MODULE / "web" / "index.html"
OUT = MODULE / "WebDashboardPage.h"
LIMIT_BYTES = 40 * 1024
DELIM = "DASHPAGE"


def minify(html: str) -> str:
    lines = []
    for line in html.splitlines():
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        lines.append(s)
    return "\n".join(lines)


def render(page: str) -> str:
    if f'){DELIM}"' in page:
        raise SystemExit(f"error: page contains the raw string end ){DELIM}\"")
    return (
        "// GENERATED by tools/embed_page.py from web/index.html.\n"
        "// Do not edit by hand: edit web/index.html and rerun the tool.\n"
        "#ifndef WEB_DASHBOARD_PAGE_H\n"
        "#define WEB_DASHBOARD_PAGE_H\n\n"
        "#include <Arduino.h>\n\n"
        f'static const char DASH_PAGE[] PROGMEM = R"{DELIM}({page}){DELIM}";\n'
        "static const size_t DASH_PAGE_LEN = sizeof(DASH_PAGE) - 1;\n\n"
        "#endif // WEB_DASHBOARD_PAGE_H\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="only check that WebDashboardPage.h is current")
    args = parser.parse_args()

    page = minify(SRC.read_text(encoding="utf-8"))
    size = len(page.encode("utf-8"))
    if size > LIMIT_BYTES:
        print(f"error: page is {size} bytes, limit is {LIMIT_BYTES}", file=sys.stderr)
        return 1

    header = render(page)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != header:
            print("error: WebDashboardPage.h is out of date; run tools/embed_page.py",
                  file=sys.stderr)
            return 1
        print(f"ok: WebDashboardPage.h is current ({size} bytes)")
        return 0

    OUT.write_text(header, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: page {size} bytes ({size / LIMIT_BYTES:.0%} of {LIMIT_BYTES // 1024} KB limit)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
